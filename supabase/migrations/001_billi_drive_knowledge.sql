-- BILLI R-20 private Drive knowledge ingestion. Run in Supabase SQL Editor.
create extension if not exists vector with schema extensions;
create table if not exists public.billi_drive_files (
  id text primary key, name text not null, mime_type text, modified_time timestamptz,
  web_view_link text, checksum text, synced_at timestamptz default now(),
  language text check (language in ('en','ta','si','unknown')),
  private_source boolean not null default true
);
create table if not exists public.billi_knowledge_chunks (
  id bigint generated by default as identity primary key,
  drive_file_id text not null references public.billi_drive_files(id) on delete cascade,
  chunk_index integer not null, content text not null, language text not null default 'unknown',
  embedding extensions.vector(768), metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz default now(), unique(drive_file_id,chunk_index)
);
create index if not exists billi_chunks_embedding_idx on public.billi_knowledge_chunks using hnsw (embedding extensions.vector_cosine_ops);
create index if not exists billi_chunks_language_idx on public.billi_knowledge_chunks(language);
create table if not exists public.billi_drive_oauth_tokens (
  id text primary key default 'owner', encrypted_token text not null, updated_at timestamptz default now()
);
alter table public.billi_drive_files enable row level security;
alter table public.billi_knowledge_chunks enable row level security;
alter table public.billi_drive_oauth_tokens enable row level security;
-- Intentionally no client policies. Service-role access only; keep keys server-side.
create or replace function public.billi_match_knowledge(query_embedding extensions.vector(768), match_count int default 6, language_filter text default null)
returns table(id bigint, drive_file_id text, chunk_index int, content text, language text, metadata jsonb, similarity float)
language sql stable security definer set search_path=public,extensions as $$
 select c.id,c.drive_file_id,c.chunk_index,c.content,c.language,c.metadata,
 1-(c.embedding <=> query_embedding) as similarity
 from public.billi_knowledge_chunks c
 where (language_filter is null or c.language=language_filter or c.language='unknown')
 order by c.embedding <=> query_embedding limit greatest(1,least(match_count,20));
$$;
